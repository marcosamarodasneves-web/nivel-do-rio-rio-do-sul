create table if not exists public.river_forecasts (
    id              bigint generated by default as identity primary key,
    -- DOM_TITO | RICARDO_KANITZ | BR470 (os nomes das pontes do app)
    bridge          text            not null,
    -- quantas horas à frente: 1, 2 ou 3
    horizon_h       smallint        not null default 1 check (horizon_h between 1 and 3),
    -- horário previsto para a leitura (base_time + horizon_h horas)
    target_time     timestamptz     not null,
    -- pode ficar ausente quando outro cliente atualiza apenas a conferência
    base_time       timestamptz,
    station_id      text            not null default '',
    -- id aleatório e anônimo do aparelho; não é dado pessoal
    device_bucket   text            not null default '',
    current_level   double precision not null default 0,   -- nível na hora da conta (m)
    predicted_level double precision not null default 0,   -- nível previsto (m)
    band_cm         double precision not null default 0,   -- margem informada no card (cm)
    tolerance_cm    double precision not null default 5,   -- tolerância usada na conferência
    confidence      smallint        not null default 0,    -- 0 baixa, 1 média, 2 alta
    outcome         text            not null default 'pendente'
                      check (outcome in ('pendente','dentro','quase','fora','sem_medicao')),
    actual_level    double precision,                      -- nível que o rio marcou (m)
    actual_time     timestamptz,                           -- horário dessa leitura
    error_cm        double precision,                      -- previsto - real, em cm
    created_at      timestamptz     not null default now(),
    updated_at      timestamptz     not null default now(),
    -- uma linha por ponte, horário-alvo e horizonte: o app reenvia sem duplicar
    constraint river_forecasts_bridge_target_time_horizon_key unique (bridge, target_time, horizon_h)
);

create index if not exists river_forecasts_bridge_horizon_time_idx
    on public.river_forecasts (bridge, horizon_h, target_time desc);
create index if not exists river_forecasts_outcome_idx
    on public.river_forecasts (outcome);

comment on table public.river_forecasts is
    'Previsões de nível (1, 2 e 3 horas) calculadas pelo app Nível do Rio e a conferência com o nível real da estação.';

-- updated_at automático em cada gravação do app
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists river_forecasts_touch on public.river_forecasts;
create trigger river_forecasts_touch
    before update on public.river_forecasts
    for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------
-- Segurança: RLS ligado, com leitura e escrita liberadas para a chave anon
-- (foi a opção escolhida; para fechar depois, basta trocar `using (true)`
--  por uma comparação com um cabeçalho/token próprio do app).
-- ---------------------------------------------------------------------
alter table public.river_forecasts enable row level security;
-- Grants explícitos: o Supabase já concede esses privilégios por padrão, mas assim o script
-- funciona em qualquer Postgres e a chave `anon` consegue inserir (o `id` é identity, por isso
-- a sequência também precisa de uso).
grant select, insert, update on public.river_forecasts to anon, authenticated;
grant usage, select on sequence public.river_forecasts_id_seq to anon, authenticated;

drop policy if exists river_forecasts_anon_select on public.river_forecasts;
create policy river_forecasts_anon_select on public.river_forecasts
    for select to anon, authenticated using (true);

drop policy if exists river_forecasts_anon_insert on public.river_forecasts;
create policy river_forecasts_anon_insert on public.river_forecasts
    for insert to anon, authenticated with check (true);

drop policy if exists river_forecasts_anon_update on public.river_forecasts;
create policy river_forecasts_anon_update on public.river_forecasts
    for update to anon, authenticated using (true) with check (true);

-- ---------------------------------------------------------------------
-- Visão pronta para acompanhar a consolidação dos dados (dia a dia).
-- ---------------------------------------------------------------------
drop view if exists public.river_forecasts_accuracy;
create view public.river_forecasts_accuracy as
select
    bridge,
    horizon_h,
    date_trunc('day', target_time at time zone 'America/Sao_Paulo')::date as dia,
    count(*)                                                              as previsoes,
    count(*) filter (where outcome <> 'pendente')                         as conferidas,
    count(*) filter (where outcome = 'dentro')                            as dentro_da_margem,
    count(*) filter (where outcome = 'quase')                             as quase,
    count(*) filter (where outcome = 'fora')                              as fora,
    count(*) filter (where outcome = 'sem_medicao')                       as sem_medicao,
    round(100.0 * count(*) filter (where outcome = 'dentro')
          / nullif(count(*) filter (where outcome in ('dentro','quase','fora')), 0))
                                                                          as pct_dentro,
    round(avg(abs(error_cm)) filter (where outcome in ('dentro','quase','fora'))::numeric, 1)
                                                                          as erro_medio_cm
from public.river_forecasts
group by 1, 2, 3
order by 3 desc, 1, 2;

grant select on public.river_forecasts_accuracy to anon, authenticated;

